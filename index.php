    <script>
        $(document).ready(function() {
            var $carousel = $('.carousel');
            var $items = $('.carousel-item');
            var totalItems = $items.length;
            var currentPosition = 0;

            // Function to calculate the number of visible items based on screen width
            function calculateItemsVisible() {
                if ($(window).width() >= 768) {
                    return 3; // Display 3 items on larger screens
                } else if ($(window).width() >= 480) {
                    return 2; // Display 2 items on screens up to 768px wide
                } else {
                    return 1; // Display 1 item on screens up to 480px wide
                }
            }

            // Function to update the carousel based on the current screen width
            function updateCarousel() {
                var itemsVisible = calculateItemsVisible();
                var itemWidth = $carousel.width() / itemsVisible;
                $items.css('width', itemWidth);
                $carousel.css('transform', 'translateX(' + -currentPosition * itemWidth + 'px)');
            }

            updateCarousel();

            // Handle window resize to update the carousel
            $(window).resize(function() {
                updateCarousel();
            });

            $('.next').click(function() {
                var itemsVisible = calculateItemsVisible();
                if (currentPosition < totalItems - itemsVisible) {
                    currentPosition += 1;
                } else {
                    currentPosition = 0; // Wrap around to the first item
                }
                $carousel.css('transform', 'translateX(' + -currentPosition * $items.outerWidth(true) + 'px)');
            });

            $('.prev').click(function() {
                var itemsVisible = calculateItemsVisible();
                if (currentPosition > 0) {
                    currentPosition -= 1;
                } else {
                    currentPosition = totalItems - itemsVisible; // Wrap around to the last visible item
                }
                $carousel.css('transform', 'translateX(' + -currentPosition * $items.outerWidth(true) + 'px)');
            });
        });
    </script>
